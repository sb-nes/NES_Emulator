struct FrameTimer { // Everything's public
	std::chrono::time_point<std::chrono::steady_clock> start, end;
	std::chrono::duration<float> duration;

	FrameTimer() {
		start = std::chrono::high_resolution_clock::now();
	}

	~FrameTimer() {
		end = std::chrono::high_resolution_clock::now();
		duration = end - start;

#if FRAME_LIMITER
		while (duration.count() < FRAME_PER_SECOND) {
			end = std::chrono::high_resolution_clock::now();
			duration = end - start;
		}
#endif
		float s = duration.count(); // result in seconds

#if TIMING_DEBUG
		++_frameCount;
		if (_frameCount == 0) _avgTime = s;
		else _avgTime += s;

		if (_frameCount >= 10) {
			_avgTime /= 10.f;
		}
		if (_frameCount >= 10) {
			std::cout << "Last Frame Time: " << s << "s\n";
			std::cout << "FPS: " << 1.f / _avgTime << " Frames/sec\n";
			_frameCount = 0;
		}
#else
		++_frameCount;
		if (_frameCount == 0) _avgTime = s;
		else _avgTime += s;

		if (_frameCount >= 10) {
			_frames_per_sec = (int)_avgTime / 5;
			_frameCount = 0;
		}
#endif
	}
};

